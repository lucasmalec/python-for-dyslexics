"""
Task 3.11: Circle Area Formula
EN: Calculate the area of a circle with radius 5 (assume pi = 3.14159).
PL: Oblicz pole koła o promieniu 5 (przyjmij π = 3.14).
Standard: PEP 8 (<= 88 characters)
"""

radius = 5
pi = 3.1415926535
area = pi * (radius ** 2)

print(f"Circle radius: {radius}")
print(f"Circle area:   {area:.2f}")
