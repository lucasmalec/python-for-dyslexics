"""
Task 3.10: Arithmetic Mean
EN: Calculate the arithmetic mean of three numbers: 12, 15, 20.
PL: Oblicz średnią arytmetyczną trzech liczb: 12, 15, 20.
Standard: PEP 8 (<= 88 characters)
"""

n1, n2, n3 = 12, 15, 20
mean = (n1 + n2 + n3) / 3

print(f"Numbers: {n1}, {n2}, {n3}")
print(f"Arithmetic mean: {mean:.2f}")
